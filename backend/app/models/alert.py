import enum
from datetime import datetime

from sqlalchemy import Boolean, DateTime, Enum, Float, ForeignKey, Index, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base, TimestampMixin
from app.models.risk_assessment import RiskLevel

# Phase 5: Alert.severity reuses RiskAssessment's own RiskLevel (low/moderate/
# high/severe) rather than a separate ADVISORY/WARNING/SEVERE vocabulary —
# alerts are generated FROM risk assessments (app/services/alert_service.py),
# so both must speak the same scale with the same documented thresholds
# (app/services/risk_engine/thresholds.py's score_to_level()). Nothing had
# ever been written to this table before Phase 5 (see CLAUDE.md), so this is
# a clean redesign, not a breaking change to working data.


class AlertStatus(str, enum.Enum):
    ACTIVE = "active"
    RESOLVED = "resolved"
    EXPIRED = "expired"


class Alert(Base, TimestampMixin):
    """A warning bulletin for one grid cell, generated by
    `app/services/alert_service.py` from a real `RiskAssessment` (and, for
    thunderstorm, optionally a real `/predictions` classification — see that
    module's docstring for exactly which hazards use which evidence and why).

    One alert = one grid cell + one hazard type: if several nearby grid
    cells independently cross the alert threshold for the same hazard at the
    same time, that's several alerts, not one multi-grid bulletin — this
    matches the granularity risk assessments and predictions already use
    (one row per grid cell) and needs no spatial-clustering logic Phase 5
    doesn't ask for.

    Append-only history + in-place lifecycle: a row's `status` moves
    active → resolved (conditions subsided) or active → expired
    (`expires_at` passed before resolution) in place — see alert_service.py
    for exactly when each transition happens. `alert_key` is how duplicate
    prevention finds "is there already an active alert for this hazard on
    this grid cell" without creating a second row for the same ongoing
    event.
    """

    __tablename__ = "alerts"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)

    # f"{hazard_type}:{grid_cell_id}" — looked up before creating a new alert
    # so repeated pipeline runs update the existing active alert instead of
    # duplicating it (see alert_repository.find_active_by_key). Not a hard
    # unique constraint on its own (the same key legitimately repeats once an
    # old alert resolves/expires and a new event starts) — enforced instead
    # as "at most one ACTIVE row per key" by a partial unique index, below.
    alert_key: Mapped[str] = mapped_column(String(120), nullable=False)

    grid_cell_id: Mapped[str] = mapped_column(
        String(40), ForeignKey("grid_cells.id", ondelete="CASCADE"), nullable=False
    )
    location_id: Mapped[str | None] = mapped_column(
        String(50), ForeignKey("locations.id", ondelete="SET NULL"), nullable=True
    )

    title: Mapped[str] = mapped_column(String(150), nullable=False)
    hazard_type: Mapped[str] = mapped_column(String(50), nullable=False)
    severity: Mapped[RiskLevel] = mapped_column(Enum(RiskLevel, name="risk_level"), nullable=False)
    status: Mapped[AlertStatus] = mapped_column(
        Enum(AlertStatus, name="alert_status"), nullable=False, default=AlertStatus.ACTIVE
    )

    location_label: Mapped[str] = mapped_column(String(150), nullable=False)
    risk_score: Mapped[int] = mapped_column(Integer, nullable=False)
    # Why this alert fired, in the evidence's own words (e.g. the hazard
    # module's indicator labels/notes, or the ML prediction's own metrics) —
    # never a generic templated sentence, so a reader can see exactly what
    # measurement or forecast triggered it.
    evidence: Mapped[str] = mapped_column(Text, nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=False)
    recommended_action: Mapped[str] = mapped_column(Text, nullable=False)
    confidence: Mapped[float | None] = mapped_column(Float, nullable=True)

    # "rule-based-v1" | "ml-v1" | "combined" — which engine(s) actually
    # produced the evidence above. Required, never inferred, so a rule-based
    # estimate can never be mislabeled as an ML prediction or vice versa.
    source: Mapped[str] = mapped_column(String(30), nullable=False)

    issued_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    resolved_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    last_seen_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False
    )  # updated every pipeline run that re-confirms this alert is still warranted

    acknowledged: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    acknowledged_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    grid_cell: Mapped["GridCell"] = relationship(back_populates="alerts")

    __table_args__ = (
        Index("ix_alerts_status_severity", "status", "severity"),
        Index("ix_alerts_issued_at", "issued_at"),
        Index(
            "ux_alerts_active_key",
            "alert_key",
            unique=True,
            postgresql_where=(status == AlertStatus.ACTIVE),
        ),
    )

    def __repr__(self) -> str:
        return f"<Alert {self.id} {self.severity}/{self.status} {self.title!r}>"
